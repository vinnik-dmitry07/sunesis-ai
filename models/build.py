"""Rebuilds every model, the page payload and the checks, in order. Does not download anything.

Steps that need raw downloads (peer SEC facts, benchmark datasets) run only when those files exist;
otherwise the committed outputs are used and the step is reported as skipped. Run `bash models/data/fetch.sh` first
for a full rebuild. The Excel check runs only on Windows with Microsoft Excel installed.
Run:  python -I models/build.py [--no-excel]
"""
import json
import pathlib
import shutil
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
M = ROOT / "models"
PY = [sys.executable, "-I"]
log = []


def run(label, cmd, required=True):
    r = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True, encoding="utf-8", errors="replace")
    ok = r.returncode == 0
    tail = (r.stdout.strip().splitlines() or [""])[-1][:300]
    log.append({"step": label, "ok": ok, "output": tail if ok else (r.stdout + r.stderr)[-1500:]})
    print(("ok   " if ok else "FAIL ") + label + ("" if ok else "\n" + (r.stdout + r.stderr)[-1500:]))
    if required and not ok:
        write_report()
        sys.exit(1)
    return ok


def skip(label, why):
    log.append({"step": label, "ok": None, "output": why})
    print("skip " + label + ": " + why)


def write_report():
    L = ["# Build and checks", "", "Generated by `python -I models/build.py`.", "", "| Step | Result | Last line of output |", "|---|---|---|"]
    for x in log:
        L.append(f"| {x['step']} | {'pass' if x['ok'] else 'skipped' if x['ok'] is None else 'FAIL'} | {x['output'].replace('|', '/').replace(chr(10), ' ')} |")
    (ROOT / "reports" / "05-checks.md").write_text("\n".join(L) + "\n", encoding="utf-8")


run("Stage 1 measurement with the page engine", ["node", "models/measure.mjs"])
run("Stage 2 dated assumptions", PY + ["models/stage2_assumptions.py"])
run("Scenarios evaluated with the page engine", ["node", "models/scenarios.mjs"])
run("Resolved Ginzu inputs per case", ["node", "models/export_ginzu_cases.mjs"])
run("Python DCF port", PY + ["models/dcf.py"])
run("Row-by-row DCF comparison", PY + ["models/compare_dcf.py"])
peers = all((M / "data" / "sec" / f"{t}_companyfacts.json").exists() for t in ("chd", "clx", "enr", "rpm", "kwr"))
if peers:
    run("Peer facts as of 29 Aug 2025", PY + ["models/comps_extract.py"])
    run("Methods workbook (DCF, EVA, DDM, LBO, synergies, comps, precedents)", PY + ["models/methods.py"])
else:
    skip("Peer facts and methods workbook", "peer SEC facts missing; run bash models/data/fetch.sh")
bench = (M / "data" / "benchmarks" / "financebench" / "financebench_open_source.jsonl").exists()
if bench:
    run("Benchmark records merged", PY + ["models/questions/extract.py"])
    run("WD-40 questions and answers", PY + ["models/questions/build_questions.py"])
else:
    skip("Benchmark questions", "benchmark files missing; using the committed models/questions/questions.json")
if peers:
    run("Page engine check of every model formula", ["node", "models/verify_cells.mjs", "models/out/valuation_book/valuation_cells.json"])
    if "--no-excel" not in sys.argv and sys.platform == "win32" and shutil.which("python"):
        ok = run("Excel full recalculation, save and reopen", PY + ["models/verify_excel.py", "models/out/valuation_book/wd40_valuation.xlsx",
                                                                    "models/out/valuation_book/valuation_cells.json"], required=False)
        if ok:
            (M / "excel").mkdir(exist_ok=True)
            shutil.copyfile(M / "out" / "valuation_book" / "wd40_valuation.recalculated.xlsx", M / "excel" / "wd40_valuation.xlsx")
    else:
        skip("Excel check", "needs Windows with Microsoft Excel")
    run("Page payload", ["node", "models/build_payload.mjs"])
    run("Payload embedded in index.html", PY + ["models/inject.py"])
    run("Payload embedding is idempotent", PY + ["models/inject.py", "--check"])
write_report()
print("report: reports/05-checks.md")
