"""Rebuilds every model, the page payload and the checks, in order. Does not download anything.

Release mode (default) treats every check as mandatory: missing raw inputs, a failed test, a failed engine
check or a failed Excel recalculation stops the build. `--partial` (implied by `--no-excel`) allows skipped
steps and labels the result partial; a partial build is never release-ready.
Check results are written to models/out/checks.json with the sha256 of each artifact they certify; the page
payload reads its statuses from there.
Run:  python -I models/build.py [--partial] [--no-excel]
"""
import hashlib
import json
import pathlib
import shutil
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
M = ROOT / "models"
OUT = M / "out"
PY = [sys.executable, "-I"]
PARTIAL = "--partial" in sys.argv or "--no-excel" in sys.argv
log, skipped = [], []
checks = {"mode": "partial" if PARTIAL else "release"}


def sha(path):
    return hashlib.sha256(pathlib.Path(path).read_bytes()).hexdigest()


def run(label, cmd, env=None):
    r = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True, encoding="utf-8", errors="replace", env=env)
    ok = r.returncode == 0
    tail = (r.stdout.strip().splitlines() or [""])[-1][:300]
    log.append({"step": label, "ok": ok, "output": tail if ok else (r.stdout + r.stderr)[-1500:]})
    print(("ok   " if ok else "FAIL ") + label + ("" if ok else "\n" + (r.stdout + r.stderr)[-1500:]))
    if not ok:
        finish(failed=True)
    return ok


def skip(label, why):
    if not PARTIAL:
        log.append({"step": label, "ok": False, "output": f"required input missing: {why}"})
        print(f"FAIL {label}: {why} (release builds need it; use --partial to continue without it)")
        finish(failed=True)
    skipped.append(label)
    log.append({"step": label, "ok": None, "output": why})
    print("skip " + label + ": " + why)


def finish(failed=False):
    readiness = "failed" if failed else ("partial: " + "; ".join(skipped) if skipped or PARTIAL else "release-ready")
    checks["readiness"] = readiness
    OUT.mkdir(exist_ok=True)
    (OUT / "checks.json").write_text(json.dumps(checks, indent=1), encoding="utf-8")
    L = ["# Build and checks", "", f"Generated by `python -I models/build.py{' --partial' if PARTIAL else ''}`. Readiness: **{readiness}**.", "",
         "| Step | Result | Last line of output |", "|---|---|---|"]
    for x in log:
        L.append(f"| {x['step']} | {'pass' if x['ok'] else 'skipped' if x['ok'] is None else 'FAIL'} | {x['output'].replace('|', '/').replace(chr(10), ' ')[:400]} |")
    with open(ROOT / "reports" / "05-checks.md", "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(L) + "\n")
    print(f"readiness: {readiness}; report: reports/05-checks.md")
    sys.exit(1 if failed else 0)


run("Stage 1 measurement with the page engine", ["node", "models/measure.mjs"])
run("Stage 2 dated assumptions", PY + ["models/stage2_assumptions.py"])
run("Scenarios evaluated with the page engine", ["node", "models/scenarios.mjs"])
run("Resolved Ginzu inputs per case", ["node", "models/export_ginzu_cases.mjs"])
run("Unsupported Ginzu features are refused", ["node", "--test", "models/tests/scope.test.mjs"])
run("Python DCF port", PY + ["models/dcf.py"])
run("Row-by-row DCF comparison", PY + ["models/compare_dcf.py"])
checks["dcfCompare"] = json.loads((OUT / "dcf" / "compare.json").read_text())["inputs"]

peers = all((M / "data" / "sec" / f"{t}_companyfacts.json").exists() for t in ("chd", "clx", "enr", "rpm", "kwr"))
if peers:
    run("Peer facts as of 29 Aug 2025", PY + ["models/comps_extract.py"])
    run("Methods workbook (DCF, EVA, DDM, LBO, synergies, comps, precedents)", PY + ["models/methods.py"])
else:
    skip("Peer facts and methods workbook", "peer SEC facts missing; run bash models/data/fetch.sh")

lock = json.loads((M / "data" / "benchmarks" / "manifest.json").read_text(encoding="utf-8"))["sources"]
bench = all((M / "data" / "benchmarks" / s["filename"]).exists() for s in lock)
if bench:
    run("Benchmark records merged", PY + ["models/questions/extract.py"])
    run("WD-40 questions and answers", PY + ["models/questions/build_questions.py"])
else:
    skip("Benchmark questions", "benchmark files missing; the committed models/questions/questions.json is used unchanged")

cells = OUT / "valuation_book" / "valuation_cells.json"
if cells.exists():
    run("Page engine check of every model formula", ["node", "models/verify_cells.mjs", str(cells.relative_to(ROOT))])
    eng = json.loads(cells.with_suffix(".engine-check.json").read_text())
    if eng["cellsSha256"] != sha(cells):
        log.append({"step": "Engine check covers the current cells", "ok": False, "output": "hash mismatch"})
        finish(failed=True)
    checks["engine"] = {k: eng[k] for k in ("cellsSha256", "engineSha256", "checked", "failed", "worstRelative")}
    xlsx = OUT / "valuation_book" / "wd40_valuation.xlsx"
    if "--no-excel" in sys.argv or sys.platform != "win32":
        skip("Excel full recalculation, save and reopen", "needs Windows with Microsoft Excel")
    else:
        run("Excel full recalculation, save and reopen", PY + ["models/verify_excel.py", str(xlsx.relative_to(ROOT)), str(cells.relative_to(ROOT))])
        xr = json.loads(cells.with_suffix(".excel-check.json").read_text())
        if xr["cellsSha256"] != sha(cells) or xr["inputSha256"] != sha(xlsx):
            log.append({"step": "Excel check covers the current workbook", "ok": False, "output": "hash mismatch"})
            finish(failed=True)
        (M / "excel").mkdir(exist_ok=True)
        shutil.copyfile(OUT / "valuation_book" / "wd40_valuation.recalculated.xlsx", M / "excel" / "wd40_valuation.xlsx")
        published = sha(M / "excel" / "wd40_valuation.xlsx")
        if published != xr["recalculatedSha256"]:
            log.append({"step": "Published workbook is the checked file", "ok": False, "output": "hash mismatch"})
            finish(failed=True)
        checks["excel"] = {**{k: xr[k] for k in ("inputSha256", "recalculatedSha256", "cellsSha256", "checked", "failed", "worstRelative")},
                           "publishedPath": "models/excel/wd40_valuation.xlsx", "publishedSha256": published}
        # Input changes made inside Excel, compared with a fresh Python build of the same change.
        variants = [("wacc0:base=0.065", "Scenario inputs!D21=0.065", "Base WACC 6.5%"),
                    ("growth25:bull=0.09", "Scenario inputs!E12=0.09", "Bull years 2-5 growth 9%"),
                    ("growthT:bear=0.015", "Scenario inputs!C13=0.015", "Bear terminal growth 1.5%")]
        checks["excelInputChanges"] = []
        for spec, cell, label in variants:
            run(f"Python DCF with {label}", PY + ["models/dcf.py", "--variant", spec])
            run(f"Excel recalculation with {label}", PY + ["models/verify_excel.py", "models/out/dcf/wd40_dcf.xlsx", "models/out/dcf/variant/dcf_cells.json", cell])
            vr = json.loads((OUT / "dcf" / "variant" / "dcf_cells.excel-check.json").read_text())
            checks["excelInputChanges"].append({"change": label, "cell": cell, "checked": vr["checked"], "failed": vr["failed"], "worstRelative": vr["worstRelative"]})
    (OUT / "checks.json").write_text(json.dumps(checks, indent=1), encoding="utf-8")
    run("Page payload", ["node", "models/build_payload.mjs"])
    run("Payload embedded in index.html", PY + ["models/inject.py"])
    run("Payload embedding is idempotent", PY + ["models/inject.py", "--check"])
else:
    skip("Engine check, Excel check and page payload", "no methods workbook was built")
finish()
